"""Self-contained HTML reports for dubs and batches.

The JSON and Markdown reports are for machines and terminals; the HTML
report is the one you open in a browser and hand to a reviewer. It is
stdlib-only (``html.escape`` + string building, no template engine, no
external assets) so the file works offline, straight off disk:

* :func:`render_html_report` — one dubbed transcript: a verdict banner,
  the MOS proxy as a bar, the headline metrics, and a per-segment table
  that flags the exact segments that drifted or stretched too far.
* :func:`render_batch_html` — a whole batch run: per-job table with
  status, verdict, MOS proxy and WER, plus the failures listed.

All text that comes from a transcript or a job name is escaped, so a
segment reading ``<script>alert(1)</script>`` renders as text, never
as markup.
"""

from __future__ import annotations

import html
from typing import TYPE_CHECKING

from video_dubber.assemble import DubReport

if TYPE_CHECKING:
    from video_dubber.batch import BatchSummary

__all__ = ["render_batch_html", "render_html_report"]

_CSS = """
body { font-family: system-ui, sans-serif; max-width: 900px; margin: 2em auto;
       padding: 0 1em; color: #1a1a1a; }
.banner { padding: 1em 1.2em; border-radius: 8px; font-size: 1.2em; font-weight: 600; }
.banner.good { background: #dcfce7; color: #166534; }
.banner.review { background: #fef3c7; color: #92400e; }
.mos { margin: 1em 0; }
.mos .bar { background: #e5e7eb; border-radius: 4px; height: 14px; overflow: hidden; }
.mos .fill { background: #2563eb; height: 100%; }
table { border-collapse: collapse; width: 100%; margin: 1em 0; }
th, td { border: 1px solid #d1d5db; padding: 0.4em 0.6em; text-align: left; }
th { background: #f3f4f6; }
tr.flagged td { background: #fef3c7; }
td.num, th.num { text-align: right; }
.meta { color: #6b7280; font-size: 0.9em; }
"""

_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title}</title>
<style>{css}</style>
</head>
<body>
<h1>{title}</h1>
{banner}
{body}
<p class="meta">Generated by video-dubber. MOS proxy is a heuristic (1-5),
not a listening test.</p>
</body>
</html>
"""


def _page(title: str, banner: str, body: str) -> str:
    return _TEMPLATE.format(title=html.escape(title), css=_CSS, banner=banner, body=body)


def _metric_rows(pairs: list[tuple[str, str]]) -> str:
    rows = "".join(
        f"<tr><th>{html.escape(label)}</th><td>{value}</td></tr>" for label, value in pairs
    )
    return f"<table>\n{rows}\n</table>"


def render_html_report(report: DubReport, title: str = "Dub quality report") -> str:
    """Render one :class:`~video_dubber.assemble.DubReport` as HTML.

    The verdict banner is green for ``good`` and amber for ``review``;
    the per-segment table flags rows with drift over 0.10s or a fit
    factor outside 0.8–1.25 — the same thresholds the report itself
    uses — so the reviewer sees exactly which segments to re-record.
    """
    verdict = report.verdict
    banner = (
        f'<p class="banner {html.escape(verdict)}">'
        f"Verdict: {html.escape(verdict)}"
        f" &mdash; MOS proxy {report.mos_proxy:.2f} / 5</p>"
    )
    mos_pct = max(0.0, min(100.0, report.mos_proxy / 5.0 * 100.0))
    mos = (
        '<div class="mos"><div class="bar">'
        f'<div class="fill" style="width: {mos_pct:.0f}%"></div>'
        "</div></div>"
    )
    metrics: list[tuple[str, str]] = [
        ("Segments dubbed", str(report.segments_dubbed)),
        ("Total duration", f"{report.total_duration:.2f}s"),
        (
            "Mean sync drift",
            f"{report.mean_sync_drift:.3f}s (max {report.max_sync_drift:.3f}s)",
        ),
        ("Segments over 0.10s drift", str(report.segments_over_drift)),
        (
            "Mean fit factor",
            f"{report.mean_fit_factor:.3f} (max {report.max_fit_factor:.3f})",
        ),
        ("Extreme fits (outside 0.8&ndash;1.25)", str(report.extreme_fits)),
    ]
    if report.loudness_error_db is not None:
        metrics.append(("Loudness error vs original", f"{report.loudness_error_db:.2f} dB"))
    if report.translation_coverage is not None:
        metrics.append(("Translation coverage", f"{report.translation_coverage:.0%}"))
    if report.word_error_rate is not None:
        metrics.append(("Word error rate vs reference", f"{report.word_error_rate:.3f}"))
    if report.speakers_dubbed:
        metrics.append(("Speakers dubbed", str(report.speakers_dubbed)))
    if report.bed_level is not None:
        metrics.append(("Background bed level", f"{report.bed_level:.2f}"))
    if report.enhancement is not None:
        enh = report.enhancement
        metrics.append(
            (
                "Enhancement",
                (
                    f"RMS {enh.before.rms_dbfs:.1f} &rarr; {enh.after.rms_dbfs:.1f} dBFS "
                    f"(gain {enh.gain_db:+.1f} dB)"
                ),
            )
        )
    body = mos + _metric_rows(metrics)
    if report.segments:
        rows = [
            "<table>",
            (
                "<tr><th>#</th><th>Time</th><th>Speaker</th><th>Text</th>"
                '<th class="num">Drift (s)</th><th class="num">Fit</th></tr>'
            ),
        ]
        for row in report.segments:
            flagged = row.drift > 0.10 or row.fit_factor < 0.8 or row.fit_factor > 1.25
            cls = ' class="flagged"' if flagged else ""
            rows.append(
                f"<tr{cls}>"
                f"<td>{row.index}</td>"
                f"<td>{row.start:.2f}&ndash;{row.end:.2f}s</td>"
                f"<td>{html.escape(row.speaker or '-')}</td>"
                f"<td>{html.escape(row.text)}</td>"
                f'<td class="num">{row.drift:.3f}</td>'
                f'<td class="num">{row.fit_factor:.3f}</td>'
                "</tr>"
            )
        rows.append("</table>")
        body += "<h2>Segments</h2>\n" + "\n".join(rows)
    return _page(title, banner, body)


def render_batch_html(summary: BatchSummary, title: str = "Batch dub report") -> str:
    """Render a :class:`~video_dubber.batch.BatchSummary` as HTML."""
    jobs = summary.total
    banner = (
        f'<p class="banner {"good" if summary.failed == 0 else "review"}">'
        f"{summary.succeeded} ok, {summary.failed} failed, "
        f"{summary.skipped} skipped out of {jobs} jobs"
        "</p>"
    )
    metrics: list[tuple[str, str]] = [("Jobs", str(jobs))]
    if summary.mean_wer is not None:
        metrics.append(("Mean transcription WER", f"{summary.mean_wer:.3f}"))
    if summary.mean_mos is not None:
        metrics.append(("Mean MOS proxy", f"{summary.mean_mos:.2f}"))
    body = _metric_rows(metrics)
    rows = [
        "<table>",
        (
            "<tr><th>Job</th><th>Status</th><th>Verdict</th>"
            '<th class="num">MOS proxy</th><th class="num">WER</th>'
            '<th class="num">Duration</th></tr>'
        ),
    ]
    for result in summary.results:
        mos = f"{result.mos_proxy:.2f}" if result.mos_proxy is not None else "-"
        wer = f"{result.transcription_wer:.3f}" if result.transcription_wer is not None else "-"
        cls = ' class="flagged"' if result.status == "failed" else ""
        rows.append(
            f"<tr{cls}>"
            f"<td>{html.escape(result.name)}</td>"
            f"<td>{html.escape(result.status)}</td>"
            f"<td>{html.escape(result.verdict or '-')}</td>"
            f'<td class="num">{mos}</td>'
            f'<td class="num">{wer}</td>'
            f'<td class="num">{result.duration_s:.1f}s</td>'
            "</tr>"
        )
    rows.append("</table>")
    body += "\n".join(rows)
    failures = [r for r in summary.results if r.status == "failed"]
    if failures:
        body += "<h2>Failures</h2>\n<ul>\n" + "".join(
            f"<li><strong>{html.escape(r.name)}</strong>: {html.escape(r.error or '')}</li>\n"
            for r in failures
        )
        body += "</ul>"
    return _page(title, banner, body)
